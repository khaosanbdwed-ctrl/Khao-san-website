import type { Metadata } from 'next';
import { createPublicClient } from '@/lib/supabase/public';
import MenuPageClient from '@/components/menu-page-client';
import type { MenuCategory } from '@/components/menu-page-client';
import { getSiteContent } from '@/lib/cms/content';
import { encodePath } from '@/lib/site';

/**
 * The menu was fully dynamic, so all three queries below ran on every single
 * page view for content that changes a few times a year — latency on the site's
 * most-visited page, and Supabase quota spent re-fetching identical rows.
 *
 * It is cached for an hour instead. Edits do not wait for that window: every
 * write in /api/admin/menu calls revalidatePath('/menu'), so a dish saved in
 * the admin panel is live immediately. The hour is only the backstop for
 * changes made directly in the Supabase dashboard.
 */
export const revalidate = 3600;

/* The menu is the page people search for ("khao san menu"), so it carries its
   own title and description - it used to inherit the homepage's. */
export async function generateMetadata(): Promise<Metadata> {
    const { menu, site } = await getSiteContent();
    const description = menu.hero.lede || undefined;
    // openGraph replaces the layout's as a whole, so the share picture and
    // site name are carried over rather than lost.
    return {
        title: 'Menu | Khao San',
        description,
        alternates: { canonical: '/menu' },
        openGraph: {
            title: 'Menu | Khao San',
            description,
            url: '/menu',
            siteName: 'Khao San',
            type: 'website',
            images: site.seo.shareImage ? [{ url: encodePath(site.seo.shareImage), alt: 'Khao San Restaurant' }] : [],
        },
    };
}

/**
 * Point a dish at its plated photograph.
 *
 * Supabase stores the path to the original cut-out under
 * `Menu/KS Menu Webp/...`. Those are RGBA silhouettes on a transparent ground -
 * the floating-dish source material the client rejected. `menu-plated/` holds
 * the same dishes composited onto a warm ground with a contact shadow and
 * normalised framing (generated by scratchpad/plate.py; re-runnable).
 *
 * Rewritten here rather than in the database so the originals stay the record
 * of what was uploaded, and so the admin panel's upload flow is untouched. A
 * path that does not match the expected prefix is passed through unchanged, so
 * a newly uploaded dish still renders - just without the plating until the
 * script is re-run over it.
 */
const PLATED_FROM = '/assets/Menu/KS Menu Webp/';
const PLATED_TO = '/assets/menu-plated/';

function platedSrc(src: string): string {
    return src.startsWith(PLATED_FROM) ? src.replace(PLATED_FROM, PLATED_TO) : src;
}

/** A query, retried twice on failure (0.3 s, then 1 s later), so a momentary
 *  network blip between the host and Supabase never reaches a visitor. */
async function withRetry<T extends { error: { message: string } | null }>(run: () => PromiseLike<T>): Promise<T> {
    let result = await run();
    for (const wait of [300, 1000]) {
        if (!result.error) break;
        await new Promise(r => setTimeout(r, wait));
        result = await run();
    }
    return result;
}

export default async function MenuPage() {
    const supabase = createPublicClient();

    const [
        site,
        { data: categories, error: categoriesError },
        { data: items, error: itemsError },
        { data: addOns, error: addOnsError },
    ] = await Promise.all([
        getSiteContent(),
        withRetry(() => supabase.from('menu_categories').select('*').order('sort_order')),
        withRetry(() => supabase.from('menu_items').select('*').order('sort_order')),
        withRetry(() => supabase.from('menu_category_addons').select('*')),
    ]);

    /* ⚠ A FAILED QUERY MUST THROW, NOT RENDER AN EMPTY MENU. The errors used to
       be ignored, so a brief Supabase outage during the hourly refresh cached
       a menu with no dishes for the next hour. Throwing keeps the last good
       page during the hourly refresh (stale-while-revalidate serves it until
       a refresh succeeds), and at build time it stops the deploy - the
       previous deployment stays live - rather than publishing an empty menu
       (the same policy as lib/supabase/env.ts). Right after a dish is saved
       the page is re-rendered on the next visit, so an outage at that exact
       moment shows the error page until Supabase is back - then it recovers
       by itself on the next visit. */
    const failure = categoriesError || itemsError || addOnsError;
    if (failure) throw new Error(`The menu could not be loaded from Supabase: ${failure.message}`);

    const menuData: MenuCategory[] = (categories || []).map(cat => ({
        id: cat.id,
        name: cat.name,
        addOns: (addOns || [])
            .filter(a => a.category_id === cat.id)
            .map(a => ({ title: a.title, price: a.price })),
        items: (items || [])
            .filter(item => item.category_id === cat.id)
            .map(item => ({
                number: item.item_number,
                title: item.title,
                imageSrc: platedSrc(item.image_src || ''),
                price: item.price,
                groupPrice: item.group_price || undefined,
                portionNote: item.portion_note || undefined,
                description: item.description || '',
                badges: item.badges || [],
                addOnNote: item.add_on_note || undefined,
                angled: item.angled || false,
            })),
    })).filter(cat => cat.items.length > 0 || cat.addOns?.length);

    return <MenuPageClient categories={menuData} page={site.menu} />;
}
